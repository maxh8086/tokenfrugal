// Generates docs/structure/PROJECT-STRUCTURE.md from the code, the tests and the design doc.
// Usage: node scripts/build-structure.mjs          (write the document)
//        node scripts/build-structure.mjs --check  (exit 1 if the committed document is stale)
// Pure builder: buildStructure(sources) takes the file texts and returns markdown, so tests need no disk.

import { readFile, readdir, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ENGINE_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO_ROOT = path.resolve(ENGINE_DIR, '../../..');
const DESIGN_DOC = 'docs/designs/media-generator-multiformat-engine.md';
const OUT_DOC = 'docs/structure/PROJECT-STRUCTURE.md';

// Export names from one module, e.g. `export function foo`, `export const bar`, `export class Baz`.
export function exportsOf(source) {
  const names = [];
  const re = /^export\s+(?:async\s+)?(?:function\*?|const|let|class)\s+(\w+)/gm;
  let m;
  while ((m = re.exec(source)) !== null) names.push(m[1]);
  return names;
}

// Local module paths a file imports, e.g. "../lib/disk-gate.js" -> "lib/disk-gate.js".
export function importsOf(source) {
  const out = new Set();
  const re = /from\s+['"]((?:\.\.?\/)+(?:lib|bin)\/[\w.-]+\.js)['"]/g;
  let m;
  while ((m = re.exec(source)) !== null) {
    out.add(m[1].replace(/^(\.\.?\/)+/, ''));
  }
  return [...out].sort();
}

// Routes registered on the Express app, e.g. "POST /render".
export function routesOf(source) {
  const out = [];
  const re = /^app\.(get|post|put|delete)\(\s*['"]([^'"]+)['"]/gm;
  let m;
  while ((m = re.exec(source)) !== null) out.push(`${m[1].toUpperCase()} ${m[2]}`);
  return out;
}

// Design-doc decisions: table rows of section 7 whose first cell is D<n>.
export function decisionsOf(doc) {
  const out = new Map();
  for (const line of doc.split('\n')) {
    const m = /^\|\s*(D\d+)\s*\|(.*)$/.exec(line);
    if (m) out.set(m[1], line);
  }
  return out;
}

// Open items: bullets "- **O<n>** STATUS ...". Status is the first word after the ID.
export function openItemsOf(doc) {
  const out = new Map();
  const re = /^- \*\*(O\d+)\*\*\s+(\S+)/gm;
  let m;
  while ((m = re.exec(doc)) !== null) out.set(m[1], m[2].replace(/[^A-Z]/g, ''));
  return out;
}

// Duplicate export names across lib modules: name -> [module paths]. Only names in two or more modules.
export function duplicateExports(modules) {
  const seen = new Map();
  for (const [file, src] of modules) {
    for (const name of exportsOf(src)) {
      if (!seen.has(name)) seen.set(name, []);
      seen.get(name).push(file);
    }
  }
  return [...seen.entries()].filter(([, files]) => files.length > 1);
}

// Build the markdown. `sources` = { modules: Map(libPath -> text), tests: Map(testPath -> text),
// server: text, pkgTestList: string[], doc: text, root: string }
export function buildStructure(sources) {
  const { modules, tests, server, doc, pkgTestList } = sources;
  const libs = [...modules.keys()].sort();

  // lib module -> test files that import it
  const testsFor = new Map(libs.map((l) => [l, []]));
  for (const [testPath, src] of tests) {
    for (const imp of importsOf(src)) {
      if (testsFor.has(imp)) testsFor.get(imp).push(testPath);
    }
  }
  const inPkgList = new Set(pkgTestList);

  // decision/open-item IDs that name each module file (by basename, e.g. disk-gate.js)
  const decisions = decisionsOf(doc);
  const openItems = openItemsOf(doc);
  const decisionsFor = new Map(libs.map((l) => [l, []]));
  for (const [id, row] of decisions) {
    for (const l of libs) {
      if (row.includes(path.basename(l))) decisionsFor.get(l).push(id);
    }
  }

  const lines = [];
  lines.push('# Project structure');
  lines.push('');
  lines.push('<!-- Generated by docker/media-generator/render-engine/scripts/build-structure.mjs. Do not edit by hand. -->');
  lines.push('');
  lines.push(`Sources: \`docker/media-generator/render-engine\` (code, tests), [${DESIGN_DOC}](../designs/media-generator-multiformat-engine.md) (decisions, open items).`);
  lines.push('');

  lines.push('## Routes');
  lines.push('');
  for (const r of routesOf(server)) lines.push(`- \`${r}\``);
  lines.push('');

  lines.push('## Modules');
  lines.push('');
  lines.push('| Module | Exports | Tests | Decisions | Note |');
  lines.push('|---|---|---|---|---|');
  for (const l of libs) {
    const exp = exportsOf(modules.get(l));
    const t = testsFor.get(l);
    const testCell = t.length
      ? t.map((p) => `${path.basename(p)}${inPkgList.has(p) ? '' : ' (not in npm test)'}`).join(', ')
      : '**none**';
    const dec = decisionsFor.get(l);
    const decCell = dec.length ? dec.join(', ') : '';
    const note = t.length ? '' : 'no test imports it';
    lines.push(`| \`${l}\` | ${exp.map((e) => `\`${e}\``).join(', ') || '-'} | ${testCell} | ${decCell} | ${note} |`);
  }
  lines.push('');

  const dups = duplicateExports(modules);
  lines.push('## Reuse: duplicate export names');
  lines.push('');
  if (dups.length === 0) lines.push('None.');
  for (const [name, files] of dups) {
    lines.push(`- \`${name}\` in ${files.map((f) => `\`${f}\``).join(', ')}. Move one copy into a shared module and import it.`);
  }
  lines.push('');

  lines.push('## Gaps');
  lines.push('');
  const untested = libs.filter((l) => testsFor.get(l).length === 0);
  const undocumented = libs.filter((l) => decisionsFor.get(l).length === 0);
  const notInList = tests ? [...tests.keys()].filter((t) => !inPkgList.has(t)) : [];
  lines.push(`- Modules with no test: ${untested.length ? untested.map((u) => `\`${u}\``).join(', ') : 'none'}`);
  lines.push(`- Modules named by no decision: ${undocumented.length ? undocumented.map((u) => `\`${u}\``).join(', ') : 'none'}`);
  lines.push(`- Test files not in \`npm test\`: ${notInList.length ? notInList.map((t) => `\`${t}\``).join(', ') : 'none'}`);
  const open = [...openItems].filter(([, s]) => s !== 'CLOSED').map(([id, s]) => `${id} (${s})`);
  lines.push(`- Open items not closed: ${open.length ? open.join(', ') : 'none'}`);
  lines.push('');

  return lines.join('\n');
}

// Reads the real files and returns the sources object for buildStructure.
export async function readSources(root = REPO_ROOT, engineDir = ENGINE_DIR) {
  const libDir = path.join(engineDir, 'lib');
  const testDir = path.join(engineDir, 'test');
  const modules = new Map();
  for (const f of (await readdir(libDir)).filter((f) => f.endsWith('.js')).sort()) {
    modules.set(`lib/${f}`, await readFile(path.join(libDir, f), 'utf8'));
  }
  const tests = new Map();
  for (const f of (await readdir(testDir)).filter((f) => f.endsWith('.test.js')).sort()) {
    tests.set(`test/${f}`, await readFile(path.join(testDir, f), 'utf8'));
  }
  const pkg = JSON.parse(await readFile(path.join(engineDir, 'package.json'), 'utf8'));
  const pkgTestList = [...(pkg.scripts.test.match(/test\/[\w.-]+\.test\.js/g) ?? [])];
  return {
    modules,
    tests,
    server: await readFile(path.join(engineDir, 'server.js'), 'utf8'),
    doc: await readFile(path.join(root, DESIGN_DOC), 'utf8'),
    pkgTestList,
    root,
  };
}

async function main() {
  const check = process.argv.includes('--check');
  const sources = await readSources();
  const md = buildStructure(sources);
  const outPath = path.join(REPO_ROOT, OUT_DOC);
  if (check) {
    let current = '';
    try {
      current = await readFile(outPath, 'utf8');
    } catch {
      // missing counts as stale
    }
    if (current !== md) {
      console.error(`${OUT_DOC} is stale. Run: node scripts/build-structure.mjs`);
      process.exit(1);
    }
    console.log(`${OUT_DOC} is up to date.`);
    return;
  }
  await mkdir(path.dirname(outPath), { recursive: true });
  await writeFile(outPath, md, 'utf8');
  console.log(`Wrote ${OUT_DOC}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
